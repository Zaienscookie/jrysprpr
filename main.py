    async def fortune(self, event: AstrMessageEvent):
        uid = event.get_sender_id()
        gid = event.get_group_id() or "私聊"
        today = _fortune_date()
        recs = self._data.setdefault(uid, {})

        # 持久化：当天已有记录直接复用（全群同步，0点刷新），只更新所在群
        rec = recs.get(today)
